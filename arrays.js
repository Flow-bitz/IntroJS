// ARRAYS
// An array stores an ordered list of values.

let colors = ["red", "blue", "green"];
console.log(colors);

// Accesssing item through index number
console.log(colors[1]);

//Changing an Array item
colors[2] = 'yellow';
console.log(colors);

//According to the Array
colors[3] = 'white';
console.log(colors);

//Using push to add items 
colors.push('black');
console.log(colors);

//Removing items
colors.pop();
console.log(colors);

//Array length
console.log(colors.length);